const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { splitSqlBatches } = require('../core/migrations')
const { createDocumentsSqlFixture } = require('./support/documents-sql-fixture')
const directory = path.resolve(__dirname, '../../db/migrations')
const initial = '068_contract_management_tasks.sql'
const repair = '078_contract_task_open_alert_index.sql'
test('indexul contractual folosește comparații acceptate, cu reparație versionată', () => {
  const source = fs.readFileSync(path.join(directory, initial), 'utf8')
  assert.ok(source.includes("WHERE cancelled_at IS NULL AND status <> N'rezolvat' AND status <> N'inchis' AND status <> N'anulat'"))
  assert.ok(fs.existsSync(path.join(directory, repair)))
})
test('index contractual pe SQL: deduplicare, stări finale, anulare și recuperare', { skip: process.env.INFRAFLOW_TEST_RELATIONAL_SQL !== '1', timeout: 240000 }, () => {
  const f = createDocumentsSqlFixture({ empty: true })
  const applySource = source => {
    f.sql('SET ANSI_NULLS ON; SET QUOTED_IDENTIFIER ON; SET ANSI_PADDING ON; SET ANSI_WARNINGS ON; SET ARITHABORT ON; SET CONCAT_NULL_YIELDS_NULL ON; SET NUMERIC_ROUNDABORT OFF;\n'+splitSqlBatches(source).map(batch => `EXEC sp_executesql N'${batch.replaceAll("'", "''")}';`).join('\n')+'\nSELECT 1;')
  }
  const apply = name => applySource(fs.readFileSync(path.join(directory, name), 'utf8'))
  apply('067_contract_management.sql')
  const source = fs.readFileSync(path.join(directory, initial), 'utf8')
  const historical = source.replace("WHERE cancelled_at IS NULL AND status <> N'rezolvat' AND status <> N'inchis' AND status <> N'anulat'", "WHERE cancelled_at IS NULL AND status NOT IN (N'rezolvat', N'inchis', N'anulat')")
  assert.throws(() => applySource(historical), error => String(error.stderr||error.message).includes("Incorrect syntax near 'NOT'"))
  apply(initial); apply(repair)
  f.sql("INSERT contract_management.contracts(numar,titlu) VALUES(N'TEST-1',N'Contract unu'),(N'TEST-2',N'Contract doi'); SELECT 1;")
  const insert = (contract, alert, status = 'deschis', cancelled = false) => f.sql(`INSERT contract_management.tasks(contract_id,alert_code,titlu,status,cancelled_at) VALUES(${contract},${alert === null ? 'NULL' : `N'${alert}'`},N'Task test',N'${status}',${cancelled ? 'SYSUTCDATETIME()' : 'NULL'}); SELECT 1;`)
  const duplicate = error => /duplicate key|unique index/i.test(String(error.stderr||error.message))
  insert(1,'A'); assert.throws(() => insert(1,'A'), duplicate)
  insert(1,'B'); insert(2,'A')
  f.sql("UPDATE contract_management.tasks SET status=N'rezolvat' WHERE contract_id=1 AND alert_code=N'A'; SELECT 1;")
  insert(1,'A'); insert(1,'A','rezolvat'); insert(1,'A','inchis'); insert(1,'A','anulat'); insert(1,'A','deschis',true)
  insert(1,null); assert.throws(() => insert(1,null), duplicate)
  apply(initial); apply(repair)
  assert.equal(f.sql('SELECT COUNT(*) FROM contract_management.tasks;').trim(),'9')
  assert.equal(f.sql("SELECT COUNT(*) FROM sys.indexes WHERE object_id=OBJECT_ID(N'contract_management.tasks') AND name=N'UX_contract_management_tasks_open_alert' AND is_unique=1 AND has_filter=1;").trim(),'1')
  // Numai baza sintetică: simulează o instalare parțială cu duplicate deja salvate.
  f.sql('DROP INDEX UX_contract_management_tasks_open_alert ON contract_management.tasks; SELECT 1;')
  insert(1,'B')
  assert.throws(() => apply(repair), error => String(error.stderr||error.message).includes('task-uri active duplicate'))
  assert.equal(f.sql("SELECT COUNT(*) FROM contract_management.tasks WHERE contract_id=1 AND alert_code=N'B';").trim(),'2')
  f.sql("UPDATE contract_management.tasks SET status=N'rezolvat' WHERE contract_id=1 AND alert_code=N'B'; SELECT 1;")
  apply(repair); apply(repair)
  assert.equal(f.sql('SELECT COUNT(*) FROM contract_management.tasks;').trim(),'10')
  insert(1,'B'); assert.throws(() => insert(1,'B'), duplicate)
  console.log(`Index contractual SQL OK: ${f.database}; duplicate refuzate, stări finale/anulări păstrate, recuperare fără ștergeri.`)
})
