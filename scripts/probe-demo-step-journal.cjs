'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const {runProbe}=require('./probe-demo-provision-reservations.cjs');
runProbe(async({database,execute,receipt,results})=>{
 for(const prefix of ['007_','008_','009_','010_']){
  const dir=path.join(__dirname,'../db/demo-platform-migrations');
  const name=fs.readdirSync(dir).find(n=>n.startsWith(prefix));
  const source=fs.readFileSync(path.join(dir,name),'utf8');
  if(prefix==='010_')await assert.rejects(execute(database,source),e=>e.sqlNumber===52801);
  await execute(database,source.replace("N'INFRAFLOW_DEMO_PLATFORM'",`N'${database}'`));
  if(prefix==='010_')assert.equal(await execute(database,source.replace("N'INFRAFLOW_DEMO_PLATFORM'",`N'${database}'`)),'PROVISION_STEP_JOURNAL_ALREADY_APPLIED');
 }
 await execute(database,"CREATE USER journal_worker WITHOUT LOGIN;GRANT EXECUTE ON OBJECT::platform.provision_lease_command TO journal_worker;GRANT EXECUTE ON OBJECT::platform.record_step_intent TO journal_worker;DENY SELECT,INSERT,UPDATE,DELETE ON SCHEMA::platform TO journal_worker;SELECT 1;");
 const call=(procedure,input,op)=>execute(database,`EXECUTE AS USER='journal_worker';BEGIN TRY EXEC platform.${procedure} ${op?"@operation='"+op+"',":''}@json=@json;REVERT;END TRY BEGIN CATCH REVERT;THROW;END CATCH;`,input).then(JSON.parse);
 const token='ab'.repeat(32),jobId=receipt.jobId;
 const claim=await call('provision_lease_command',{jobId,leaseToken:token,expectedJobRevision:0},'claim');
 const command={jobId,leaseToken:token,generation:claim.generation,expectedJobRevision:claim.jobRevision,step:'os_identity',intentId:crypto.randomUUID()};
 const first=await call('record_step_intent',command);
 assert.equal(first.executionAllowed,false);assert.equal(first.state,'intent_recorded');
 assert.deepEqual(await call('record_step_intent',command),first);
 await assert.rejects(call('record_step_intent',{...command,intentId:crypto.randomUUID()}),e=>e.sqlNumber===52812);
 await assert.rejects(call('record_step_intent',{...command,leaseToken:'cd'.repeat(32)}),e=>e.sqlNumber===52811);
 await assert.rejects(call('record_step_intent',{...command,path:'/etc'}),e=>e.sqlNumber===52810);
 await assert.rejects(call('record_step_intent',{...command,step:'shell'}),e=>e.sqlNumber===52810);
 assert.equal(await execute(database,'SELECT COUNT(*) FROM platform.provision_step_intents;'),'1');
 results.push('step_intent_exact_retry_conflict_invalid_payload_wrong_token');
 const renewed=await call('provision_lease_command',{jobId,leaseToken:token,generation:1,expectedJobRevision:1},'renew');
 const live={...command,expectedJobRevision:renewed.jobRevision};
 const raceA={...live,step:'tenant_directories',intentId:crypto.randomUUID()},raceB={...raceA,intentId:crypto.randomUUID()};
 const raced=await Promise.allSettled([call('record_step_intent',raceA),call('record_step_intent',raceB)]);
 assert.equal(raced.filter(r=>r.status==='fulfilled').length,1);
 assert.equal(raced.find(r=>r.status==='rejected').reason.sqlNumber,52812);
 const identical={...live,step:'tenant_key',intentId:crypto.randomUUID()};
 const retries=await Promise.all([call('record_step_intent',identical),call('record_step_intent',identical)]);
 assert.deepEqual(retries[0],retries[1]);
 assert.equal(await execute(database,'SELECT COUNT(*) FROM platform.provision_step_intents;'),'3');
 results.push('concurrent_conflicting_intents_single_winner_identical_retry_single_row');
 await execute(database,"EXEC(N'CREATE TRIGGER platform.fail_step_intent ON platform.provision_step_intents AFTER INSERT AS BEGIN THROW 52899,''fixture_intent_failure'',1;END;');SELECT 1;");
 const rolledBack={...live,step:'sql_database',intentId:crypto.randomUUID()};
 await assert.rejects(call('record_step_intent',rolledBack),e=>e.sqlNumber===52899);
 assert.equal(await execute(database,'SELECT COUNT(*) FROM platform.provision_step_intents;'),'3');
 await execute(database,'DROP TRIGGER platform.fail_step_intent;SELECT 1;');
 assert.equal((await call('record_step_intent',rolledBack)).intentId,rolledBack.intentId);
 assert.equal(await execute(database,'SELECT COUNT(*) FROM platform.provision_step_intents;'),'4');
 results.push('injected_insert_failure_rolls_back_same_intent_can_be_confirmed_after_recovery');
 await call('provision_lease_command',{jobId,leaseToken:token,generation:1,expectedJobRevision:renewed.jobRevision},'release');
 await assert.rejects(call('record_step_intent',command),e=>e.sqlNumber===52811);
 const next='ef'.repeat(32);
 const reclaimed=await call('provision_lease_command',{jobId,leaseToken:next,expectedJobRevision:renewed.jobRevision+1},'claim');
 await assert.rejects(call('record_step_intent',{...command,leaseToken:next,generation:2,expectedJobRevision:reclaimed.jobRevision,intentId:crypto.randomUUID()}),e=>e.sqlNumber===52813);
 await assert.rejects(execute(database,"EXECUTE AS USER='journal_worker';SELECT * FROM platform.provision_step_intents;REVERT;"),e=>e.sqlNumber===229);
 assert.equal(await execute(database,'SELECT CONVERT(int,execution_ready) FROM platform.provision_jobs;'),'0');
 results.push('step_intent_released_lease_denied_new_generation_requires_reconciliation_direct_read_denied');
}).catch(()=>{console.error('step_journal_probe_failed');process.exitCode=1;});
